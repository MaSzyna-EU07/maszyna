std::vector<std::uint8_t> rgba(std::span<std::uint8_t const> const Rgb) {
	std::vector<std::uint8_t> result;
	for (std::size_t idx = 0; idx < Rgb.size(); idx += 3) {
		result.insert(result.end(), {Rgb[idx], Rgb[idx + 1], Rgb[idx + 2], 255});
	}
	return result;
}

