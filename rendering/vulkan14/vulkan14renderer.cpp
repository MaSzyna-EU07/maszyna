float srgb_to_linear(float const Value)
{
	return (Value <= 0.04045f ? Value / 12.92f : std::pow((Value + 0.055f) / 1.055f, 2.4f));
}

// waits until Time, to a part of a millisecond: the presents of the frames generated by dlss are spread over the time of a frame. the
// sleeps of windows go by its timer, 15.6 ms unless a program asks for less, so it's a timer of a high resolution there (windows 10
// 1803 and newer), with what's left of the time (or all of it without that timer) waited out by yielding
void wait_until(std::chrono::steady_clock::time_point const Time)
{
#if defined(_WIN32)
#ifndef CREATE_WAITABLE_TIMER_HIGH_RESOLUTION
#define CREATE_WAITABLE_TIMER_HIGH_RESOLUTION 0x00000002
#endif
	static thread_local HANDLE const timer{::CreateWaitableTimerExW(nullptr, nullptr, CREATE_WAITABLE_TIMER_HIGH_RESOLUTION, TIMER_ALL_ACCESS)};
	auto const left{std::chrono::duration_cast<std::chrono::nanoseconds>(Time - std::chrono::steady_clock::now()).count()};
	if ((timer != nullptr) && (left > 200000))
	{
		// in units of 100 ns, negative for a time from now; a little early, for the yields to end it on time
		LARGE_INTEGER due;
		due.QuadPart = -static_cast<LONGLONG>((left - 100000) / 100);
		if (::SetWaitableTimerEx(timer, &due, 0, nullptr, nullptr, nullptr, 0))
		{
			::WaitForSingleObject(timer, INFINITE);
		}
	}
	while (std::chrono::steady_clock::now() < Time)
	{
		std::this_thread::yield();
	}
#else
	std::this_thread::sleep_until(Time);
#endif
}

// the threads of the renderer (gfx.threads), the calling one with them: 0, the cores less two
std::size_t render_threads()
{
	if (Global.gfx_threads > 0)
	{
		return static_cast<std::size_t>(Global.gfx_threads);
	}
	auto const cores{static_cast<std::size_t>(std::thread::hardware_concurrency())};
	return (cores > 3 ? cores - 2 : 1);
}

