// dlss on the device made for it, and the size the scene of the main window is drawn at; where it can't be had, taa instead
void vulkan14_renderer::start_dlss()
{
	auto &ctx{*m_context};
	std::string reason;
	glm::ivec2 render{0};
	auto const output{glm::max(Global.fb_size, glm::ivec2(1))};
	if (ctx.device.caps().vendor_id != nvidia_vendor_id)
	{
		reason = ctx.device.caps().device_name + " isn't an nvidia gpu";
	}
	else if (ctx.dlss.init(ctx.instance.handle(), ctx.device.physical(), ctx.device.handle(), reason))
	{
		if (ctx.dlss.plan(output, Global.gfx_dlss_native ? 1.f : Global.gfx_buffer_scale, render))
		{
			m_dlssrender = render;
			m_dlssoutput = output;
			ctx.lod_bias = ctx.dlss.lod_bias();
			vk14::log_info("dlss: the bias of the mipmaps of the scene " + std::to_string(ctx.lod_bias) + ", " + std::to_string(ctx.dlss.jitter_phases()) + " offsets of the jitter");
			// the frame generation, as far as the gpu goes (x3 and x4 from the rtx 50 series on)
			if (Global.gfx_framegeneration > 1)
			{
				auto const wanted{static_cast<std::uint32_t>(Global.gfx_framegeneration - 1)};
				m_generated = std::min(wanted, ctx.dlss.generation_max());
				if ((m_generated > 0) && (m_generated < wanted))
				{
					vk14::log_info("gfx.framegeneration x" + std::to_string(wanted + 1) + ": the gpu goes up to x" + std::to_string(m_generated + 1) + ", using that");
				}
				if ((m_generated > 0) && (false == Global.gfx_vulkan_renderthread))
				{
					vk14::log_info("gfx.framegeneration: without the render thread (gfx.vulkan.renderthread no) the frames generated are shown at once, spaced only by vsync");
				}
			}
			return;
		}
		reason = "it doesn't upscale to the window of " + std::to_string(output.x) + "x" + std::to_string(output.y);
	}
	ctx.dlss.shutdown();
	vk14::log_info("gfx.antialiasing dlss: " + reason + ", using taa");
	Global.gfx_antialiasing = global_settings::antialiasing_mode::taa;
}

bool vulkan14_renderer::Init(GLFWwindow *Window)
{
	m_contextstore = std::make_unique<context>();
	m_context = m_contextstore.get();
	auto &ctx{*m_context};

	std::string reason;
	vk14::instance_config config;
	config.validation = Global.gfx_vulkan_validation;
	config.debug_utils = (Global.gfx_vulkan_validation > 0);

	// dlss (gfx.antialiasing dlss): the extensions ngx needs go into the instance and the device; where it can't be had, taa
	if (Global.gfx_dlss() && (false == vk14::dlss::compiled()))
	{
		vk14::log_info("gfx.antialiasing dlss: this build is without the dlss sdk (WITH_DLSS), using taa");
		Global.gfx_antialiasing = global_settings::antialiasing_mode::taa;
	}
	if (Global.gfx_dlss())
	{
		vk14::dlss::instance_extensions(config.wanted_extensions);
	}
	else if (Global.gfx_framegeneration > 1)
	{
		vk14::log_info("gfx.framegeneration: it goes with gfx.antialiasing dlss or dlaa, the frames aren't generated");
	}

	auto const framesinflight{static_cast<std::uint32_t>(std::clamp(Global.gfx_vulkan_framesinflight, 2, 3))};
	auto ok{ctx.instance.create(config, reason) && ctx.device.select(ctx.instance.handle(), VK_NULL_HANDLE, Global.gfx_vulkan_device, false, reason)};
	std::vector<std::string> deviceextensions;
	if (ok && Global.gfx_dlss() && (ctx.device.caps().vendor_id == nvidia_vendor_id))
	{
		vk14::dlss::device_extensions(ctx.instance.handle(), ctx.device.physical(), deviceextensions);
	}
	ok = ok && ctx.device.create(ctx.instance, reason, deviceextensions);
	if (ok && Global.gfx_dlss())
	{
		start_dlss();
	}
	ok = ok && ctx.create_frames(framesinflight, reason) && ctx.create_core(framesinflight, reason);
	if (ok)
	{
		auto mainwindow{std::make_unique<vk14::swapchain>()};
		// the frame generation needs an image of the swapchain for each frame it makes, and reflex with it (the guide of the frame
		// generation; the latency the frames shown later add is taken back by it)
		mainwindow->set_generated(m_generated);
		mainwindow->set_low_latency(std::max(Global.gfx_reflex, m_generated > 0 ? 1 : 0));
		ok = mainwindow->create(ctx.instance, ctx.device, Window, "main window", framesinflight, reason);
		if (ok && (Global.gfx_reflex > 0) && ctx.device.low_latency_enabled() && (false == mainwindow->low_latency()) && (mainwindow->handle() != VK_NULL_HANDLE))
		{
			vk14::log_info("gfx.reflex: the driver didn't turn it on for the main window");
		}
		ctx.windows.emplace_back(std::move(mainwindow));
	}
	if (false == ok)
	{
		vk14::log_error("the renderer can't start: " + reason);
		m_contextstore.reset();
		m_context = nullptr;
		return false;
	}

	if (false == init_scene(reason))
	{
		vk14::log_error("the renderer can't start: " + reason);
		destroy_scene();
		m_contextstore.reset();
		m_context = nullptr;
		return false;
	}
	init_frame_data();

	vk14::log_info(std::to_string(framesinflight) + " frames in flight");
	// until the stages of the plan bring them, these parts of the simulator aren't there with vulkan
	vk14::log_info("not available with vulkan yet: the map panel, python screens in their own windows (N5), panels in their own windows (R5b), VR (X4)");
	// the settings of eu07.ini which only the opengl renderer takes; everything else of gfx.* is taken here as there
	vk14::log_info("settings of the opengl renderer without effect with vulkan: compresstex (the textures go to the gpu as the files give them), gfx.depthprepass.replay (the scene "
	               "is walked again for its depth), gfx.bufferstreaming, gfx.geometry.shared, gfx.format.color, gfx.format.depth, gfx.postfx.motionblur.format (the formats of the "
	               "targets are fixed), gfx.gldebug (gfx.vulkan.validation instead)");
	WriteLog("Gfx Renderer: setup complete");
	update_info();
	return true;
}

bool vulkan14_renderer::AddViewport(global_settings::extraviewport_config const &conf)
{
	if (!m_context || m_viewports.empty())
	{
		return false;
	}
	viewport_config *viewport{nullptr};
	if (conf.monitor == "MAIN")
	{
		// the main window drawn with the projection of the viewport
		viewport = &m_viewports.front();
	}
	else
	{
		// a window of its own, without an opengl context, with a swapchain of its own
		auto *window{Application.window(-1, true, conf.width, conf.height, Application.find_monitor(conf.monitor), true, false)};
		if (window == nullptr)
		{
			vk14::log_error("the window of the extra viewport on " + conf.monitor + " couldn't be made");
			return false;
		}
		auto &ctx{*m_context};
		// the windows the render thread presents are left as they are until it's done
		if (auto const *failure{ctx.drain()})
		{
			report_device_lost(failure);
			return false;
		}
		auto swapchain{std::make_unique<vk14::swapchain>()};
		std::string reason;
		if (false == swapchain->create(ctx.instance, ctx.device, window, "viewport " + conf.monitor, static_cast<std::uint32_t>(ctx.frames.size()), reason))
		{
			vk14::log_error(reason);
			return false;
		}
		ctx.windows.emplace_back(std::move(swapchain));
		m_viewports.emplace_back();
		viewport = &m_viewports.back();
		viewport->window = ctx.windows.size() - 1;
	}
	if (viewport->main && (viewport->output_width > 0))
	{
		// the size dlss was planned for isn't the one of the viewport: the main window without it
		vk14::log_info("dlss: off for the main window, drawn by the viewport " + conf.monitor + " at a size of its own");
		viewport->output_width = 0;
		viewport->output_height = 0;
	}
	viewport->width = conf.width;
	viewport->height = conf.height;
	viewport->projection = conf.projection;
	viewport->proj_type = viewport_config::custom;
	viewport->draw_range = conf.draw_range;
	vk14::log_info("viewport " + conf.monitor + ": " + std::to_string(conf.width) + "x" + std::to_string(conf.height));
	return true;
}

void vulkan14_renderer::Shutdown()
{
	if (m_main != nullptr)
	{
		// a walker has nothing of its own to let go of
		return;
	}
	if (m_context)
	{
		join_walks();
	}
	if (m_context && (m_context->device.handle() != VK_NULL_HANDLE))
	{
		// the end of the renderer, not a frame: everything on the gpu has to be done, the frame of the render thread with it
		m_context->stop_render_thread();
		vkDeviceWaitIdle(m_context->device.handle());
	}
	// the geometry on the gpu goes with the context; the data of the banks stays for the simulation
	for (auto *bank : m_banks)
	{
		if (bank != nullptr)
		{
			bank->release();
		}
	}
	destroy_scene();
	m_walkers.clear();
	m_walkstreams.clear();
	m_draw.reset();
	m_contextstore.reset();
	m_context = nullptr;
}

void vulkan14_renderer::report_device_lost(char const *Where)
{
	auto &ctx{*m_context};
	if (ctx.devicelost)
	{
		return;
	}
	ctx.devicelost = true;
	// the timeline can't be read once the device is lost: the value read before then
	auto const done{std::max(ctx.completed(), ctx.lastcompleted.load())};
	std::string report{std::string("the device was lost (") + Where + "); the gpu was done with the timeline value " + std::to_string(done) + " of " + std::to_string(ctx.timelinevalue)};
	for (auto const &frame : ctx.frames)
	{
		if ((frame.done > done) && (frame.done <= ctx.timelinevalue))
		{
			report += "; frame " + std::to_string(frame.number) + " (value " + std::to_string(frame.done) + ") wasn't done, its passes: " + ctx.passes.passes_of(frame.number);
		}
	}
	// where the gpu got to (the pass it hung or failed in is after the one done last, up to the one taken in last)
	if (ctx.device.checkpoints_enabled())
	{
		report += "; the checkpoints of the graphics queue: " + ctx.passes.checkpoints(ctx.device.graphics_queue());
		if (ctx.async_compute && (ctx.device.compute_queue() != ctx.device.graphics_queue()))
		{
			report += "; of the compute queue: " + ctx.passes.checkpoints(ctx.device.compute_queue());
		}
	}
	if (auto const fault{ctx.device.fault_report()}; false == fault.empty())
	{
		report += "; " + fault;
	}
	vk14::log_error(report);
	crashreport_add_info("vulkan_device_lost", report);
}

void vulkan14_renderer::SwapBuffers()
{
	if (!m_context)
	{
		return;
	}
	auto &ctx{*m_context};
	Timer::subsystem.gfx_swap.start();

	// with the render thread the windows are presented by it (ctx.acquired was handed over to it)
	if (false == ctx.acquired.empty())
	{
		if (false == ctx.present(ctx.acquired, ctx.framecount + 1))
		{
			report_device_lost("presenting");
		}
		ctx.acquired.clear();
	}
	++ctx.framecount;

	Timer::subsystem.gfx_swap.stop();
}

void vulkan14_renderer::Frame_Start()
{
	if (!m_context || m_context->devicelost || m_context->windows.empty() || (m_context->reflex == VK_NULL_HANDLE))
	{
		return;
	}
	auto &ctx{*m_context};
	auto const &main{*ctx.windows.front()};
	if (false == main.low_latency())
	{
		return;
	}
	// the driver says how long to wait for the gpu before the input and the simulation of the frame, once between two presents. the
	// semaphore is waited for at most a while: a window without a swapchain (minimized) has nothing for the driver to measure
	if (main.latency_sleep(ctx.reflex, ctx.reflexvalue + 1))
	{
		++ctx.reflexvalue;
		VkSemaphoreWaitInfo wait{};
		wait.sType = VK_STRUCTURE_TYPE_SEMAPHORE_WAIT_INFO;
		wait.semaphoreCount = 1;
		wait.pSemaphores = &ctx.reflex;
		wait.pValues = &ctx.reflexvalue;
		vkWaitSemaphores(ctx.device.handle(), &wait, 100000000ull);
	}
	main.latency_marker(ctx.framecount + 1, VK_LATENCY_MARKER_SIMULATION_START_NV);
	main.latency_marker(ctx.framecount + 1, VK_LATENCY_MARKER_INPUT_SAMPLE_NV);
}

