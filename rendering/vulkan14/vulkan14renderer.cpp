bool vulkan14_renderer::context::create_frames(std::uint32_t const Count, std::string &Reason)
{
	auto const handle{device.handle()};

	VkSemaphoreTypeCreateInfo timelineinfo{};
	timelineinfo.sType = VK_STRUCTURE_TYPE_SEMAPHORE_TYPE_CREATE_INFO;
	timelineinfo.semaphoreType = VK_SEMAPHORE_TYPE_TIMELINE;
	timelineinfo.initialValue = 0;
	VkSemaphoreCreateInfo semaphoreinfo{};
	semaphoreinfo.sType = VK_STRUCTURE_TYPE_SEMAPHORE_CREATE_INFO;
	semaphoreinfo.pNext = &timelineinfo;
	if (!VK14_VERIFY(vkCreateSemaphore(handle, &semaphoreinfo, nullptr, &timeline)))
	{
		Reason = "no timeline semaphore";
		return false;
	}
	instance.set_object_name(handle, VK_OBJECT_TYPE_SEMAPHORE, reinterpret_cast<std::uint64_t>(timeline), "frame timeline");
	// the timeline the sleep of reflex signals
	if (device.low_latency_enabled())
	{
		if (!VK14_VERIFY(vkCreateSemaphore(handle, &semaphoreinfo, nullptr, &reflex)))
		{
			reflex = VK_NULL_HANDLE;
		}
		else
		{
			instance.set_object_name(handle, VK_OBJECT_TYPE_SEMAPHORE, reinterpret_cast<std::uint64_t>(reflex), "reflex sleep");
		}
	}

	// the async compute: a family of its own for the passes of the sky and the weather, the frames it's done with counted apart
	async_compute = Global.gfx_vulkan_asynccompute && device.families().dedicated_compute && (device.families().compute != vk14::queue_families::invalid) && (device.compute_queue() != VK_NULL_HANDLE);
	if (async_compute)
	{
		if (!VK14_VERIFY(vkCreateSemaphore(handle, &semaphoreinfo, nullptr, &compute_timeline)))
		{
			compute_timeline = VK_NULL_HANDLE;
			async_compute = false;
		}
		else
		{
			instance.set_object_name(handle, VK_OBJECT_TYPE_SEMAPHORE, reinterpret_cast<std::uint64_t>(compute_timeline), "compute timeline");
		}
	}

	frames.resize(Count);
	for (std::uint32_t i = 0; i < Count; ++i)
	{
		VkCommandPoolCreateInfo poolinfo{};
		poolinfo.sType = VK_STRUCTURE_TYPE_COMMAND_POOL_CREATE_INFO;
		poolinfo.flags = VK_COMMAND_POOL_CREATE_TRANSIENT_BIT;
		poolinfo.queueFamilyIndex = device.families().graphics;
		if (!VK14_VERIFY(vkCreateCommandPool(handle, &poolinfo, nullptr, &frames[i].pool)))
		{
			Reason = "no command pool";
			return false;
		}
		VkCommandBufferAllocateInfo bufferinfo{};
		bufferinfo.sType = VK_STRUCTURE_TYPE_COMMAND_BUFFER_ALLOCATE_INFO;
		bufferinfo.commandPool = frames[i].pool;
		bufferinfo.level = VK_COMMAND_BUFFER_LEVEL_PRIMARY;
		bufferinfo.commandBufferCount = 1;
		if (!VK14_VERIFY(vkAllocateCommandBuffers(handle, &bufferinfo, &frames[i].uploads)))
		{
			Reason = "no command buffer";
			return false;
		}
		instance.set_object_name(handle, VK_OBJECT_TYPE_COMMAND_BUFFER, reinterpret_cast<std::uint64_t>(frames[i].uploads), "uploads " + std::to_string(i));
		frames[i].compute_stream.set_compute_queue(true);
		if (async_compute)
		{
			poolinfo.queueFamilyIndex = device.families().compute;
			bufferinfo.commandPool = VK_NULL_HANDLE;
			if (VK14_VERIFY(vkCreateCommandPool(handle, &poolinfo, nullptr, &frames[i].compute_pool)))
			{
				bufferinfo.commandPool = frames[i].compute_pool;
			}
			if ((bufferinfo.commandPool == VK_NULL_HANDLE) || !VK14_VERIFY(vkAllocateCommandBuffers(handle, &bufferinfo, &frames[i].compute_buffer)))
			{
				Reason = "no command buffer of the compute queue";
				return false;
			}
			instance.set_object_name(handle, VK_OBJECT_TYPE_COMMAND_BUFFER, reinterpret_cast<std::uint64_t>(frames[i].compute_buffer), "async compute " + std::to_string(i));
		}
	}
	if (Global.gfx_vulkan_renderthread)
	{
		start_render_thread();
	}
	return true;
}

bool vulkan14_renderer::context::record(frame &Frame, bool const Uploads, bool const Compute)
{
	auto const handle{device.handle()};
	auto const start{std::chrono::steady_clock::now()};
	Frame.upload_stream.finish();
	Frame.commands.finish();
	VkCommandBufferBeginInfo begin{};
	begin.sType = VK_STRUCTURE_TYPE_COMMAND_BUFFER_BEGIN_INFO;
	begin.flags = VK_COMMAND_BUFFER_USAGE_ONE_TIME_SUBMIT_BIT;
	if (Uploads)
	{
		VK14_VERIFY(vkBeginCommandBuffer(Frame.uploads, &begin));
		Frame.upload_stream.replay(Frame.uploads);
		VK14_VERIFY(vkEndCommandBuffer(Frame.uploads));
	}
	if (Compute)
	{
		Frame.compute_stream.finish();
		VK14_VERIFY(vkBeginCommandBuffer(Frame.compute_buffer, &begin));
		Frame.compute_stream.replay(Frame.compute_buffer);
		VK14_VERIFY(vkEndCommandBuffer(Frame.compute_buffer));
	}
	// the chunks split evenly between the workers, each with a command pool of its own (a pool is used by one thread at a time);
	// which worker records a chunk doesn't matter: each chunk has a command buffer of its own, they go to the queue in their order
	auto const chunks{Frame.commands.chunks()};
	auto const threads{std::max<std::size_t>(1, std::min<std::size_t>(render_threads(), chunks))};
	while (Frame.workers.size() < threads)
	{
		VkCommandPoolCreateInfo poolinfo{};
		poolinfo.sType = VK_STRUCTURE_TYPE_COMMAND_POOL_CREATE_INFO;
		poolinfo.flags = VK_COMMAND_POOL_CREATE_TRANSIENT_BIT;
		poolinfo.queueFamilyIndex = device.families().graphics;
		VkCommandPool pool{VK_NULL_HANDLE};
		if (!VK14_VERIFY(vkCreateCommandPool(handle, &poolinfo, nullptr, &pool)))
		{
			return false;
		}
		Frame.workers.emplace_back().pool = pool;
	}
	Frame.chunks.assign(chunks, VK_NULL_HANDLE);
	workers.run(threads, threads, [&](std::size_t const Worker) {
		auto &commands{Frame.workers[Worker]};
		for (auto chunk = chunks * Worker / threads; chunk < chunks * (Worker + 1) / threads; ++chunk)
		{
			if (commands.used == commands.buffers.size())
			{
				VkCommandBufferAllocateInfo bufferinfo{};
				bufferinfo.sType = VK_STRUCTURE_TYPE_COMMAND_BUFFER_ALLOCATE_INFO;
				bufferinfo.commandPool = commands.pool;
				bufferinfo.level = VK_COMMAND_BUFFER_LEVEL_PRIMARY;
				bufferinfo.commandBufferCount = 1;
				VkCommandBuffer buffer{VK_NULL_HANDLE};
				if (!VK14_VERIFY(vkAllocateCommandBuffers(handle, &bufferinfo, &buffer)))
				{
					return;
				}
				commands.buffers.push_back(buffer);
			}
			auto const buffer{commands.buffers[commands.used++]};
			VK14_VERIFY(vkBeginCommandBuffer(buffer, &begin));
			Frame.commands.replay(chunk, buffer);
			VK14_VERIFY(vkEndCommandBuffer(buffer));
			Frame.chunks[chunk] = buffer;
		}
	});
	record_threads = threads;
	record_time = std::chrono::duration<double, std::milli>(std::chrono::steady_clock::now() - start).count();
	record_calls = Frame.commands.calls();
	record_chunks = chunks;
	return std::find(Frame.chunks.begin(), Frame.chunks.end(), VK_NULL_HANDLE) == Frame.chunks.end();
}

bool vulkan14_renderer::context::execute(render_job &Job, char const *&Failure)
{
	if (false == submit(Job, Failure))
	{
		return false;
	}
	if ((false == Job.windows.empty()) && (false == present(Job.windows, Job.present_id)))
	{
		Failure = "presenting";
		return false;
	}
	return true;
}

bool vulkan14_renderer::context::submit(render_job &Job, char const *&Failure)
{
	auto &frame{*Job.target};
	// reflex: the recording and the submit are of the frame with the id of its present
	auto const *main{windows.empty() ? nullptr : windows.front().get()};
	auto const lowlatency{(main != nullptr) && main->low_latency() && (Job.present_id > 0)};
	if (lowlatency)
	{
		main->latency_marker(Job.present_id, VK_LATENCY_MARKER_RENDERSUBMIT_START_NV);
	}
	if (false == record(frame, Job.uploaded, Job.async))
	{
		Failure = "recording a frame";
		return false;
	}
	if (Job.async)
	{
		// the passes of the compute queue, once the graphics queue is done with the frame before, which read what they write
		VkSemaphoreSubmitInfo wait{};
		wait.sType = VK_STRUCTURE_TYPE_SEMAPHORE_SUBMIT_INFO;
		wait.semaphore = timeline;
		wait.value = Job.value - 1;
		wait.stageMask = VK_PIPELINE_STAGE_2_ALL_COMMANDS_BIT;
		VkSemaphoreSubmitInfo signal{};
		signal.sType = VK_STRUCTURE_TYPE_SEMAPHORE_SUBMIT_INFO;
		signal.semaphore = compute_timeline;
		signal.value = Job.value;
		signal.stageMask = VK_PIPELINE_STAGE_2_ALL_COMMANDS_BIT;
		VkCommandBufferSubmitInfo buffer{};
		buffer.sType = VK_STRUCTURE_TYPE_COMMAND_BUFFER_SUBMIT_INFO;
		buffer.commandBuffer = frame.compute_buffer;
		VkSubmitInfo2 compute{};
		compute.sType = VK_STRUCTURE_TYPE_SUBMIT_INFO_2;
		compute.waitSemaphoreInfoCount = (Job.value > 1 ? 1 : 0);
		compute.pWaitSemaphoreInfos = &wait;
		compute.commandBufferInfoCount = 1;
		compute.pCommandBufferInfos = &buffer;
		compute.signalSemaphoreInfoCount = 1;
		compute.pSignalSemaphoreInfos = &signal;
		if (!VK14_VERIFY(vkQueueSubmit2(device.compute_queue(), 1, &compute, VK_NULL_HANDLE)))
		{
			Failure = "submitting the async compute of a frame";
			return false;
		}
	}
	// the uploads first, in the same submit: their barriers make them done before the frame uses what they copied
	std::vector<VkCommandBufferSubmitInfo> commands;
	if (Job.uploaded)
	{
		VkCommandBufferSubmitInfo info{};
		info.sType = VK_STRUCTURE_TYPE_COMMAND_BUFFER_SUBMIT_INFO;
		info.commandBuffer = frame.uploads;
		commands.push_back(info);
	}
	// the chunks of the frame in their order: a rendering suspended at the end of one is resumed at the start of the next
	for (auto const chunk : frame.chunks)
	{
		VkCommandBufferSubmitInfo info{};
		info.sType = VK_STRUCTURE_TYPE_COMMAND_BUFFER_SUBMIT_INFO;
		info.commandBuffer = chunk;
		commands.push_back(info);
	}
	VkLatencySubmissionPresentIdNV latency{};
	latency.sType = VK_STRUCTURE_TYPE_LATENCY_SUBMISSION_PRESENT_ID_NV;
	latency.presentID = Job.present_id;
	// with the async compute in two submits: the part before the split goes on at the same time as the compute queue, the rest waits
	// for it. the waits for the images of the windows and the signals go with the rest, which draws them
	std::array<VkSubmitInfo2, 2> submits{};
	std::uint32_t count{0};
	auto first{commands.size()};
	std::vector<VkSemaphoreSubmitInfo> waits;
	if (Job.async)
	{
		first = (Job.uploaded ? 1 : 0) + std::min(frame.commands.split_chunk(), frame.chunks.size());
		auto &before{submits[count++]};
		before.sType = VK_STRUCTURE_TYPE_SUBMIT_INFO_2;
		before.commandBufferInfoCount = static_cast<std::uint32_t>(first);
		before.pCommandBufferInfos = commands.data();
		VkSemaphoreSubmitInfo compute{};
		compute.sType = VK_STRUCTURE_TYPE_SEMAPHORE_SUBMIT_INFO;
		compute.semaphore = compute_timeline;
		compute.value = Job.value;
		compute.stageMask = VK_PIPELINE_STAGE_2_ALL_COMMANDS_BIT;
		waits.push_back(compute);
	}
	waits.insert(waits.end(), Job.waits.begin(), Job.waits.end());
	auto &submit{submits[count++]};
	submit.sType = VK_STRUCTURE_TYPE_SUBMIT_INFO_2;
	if (lowlatency)
	{
		submit.pNext = &latency;
	}
	submit.waitSemaphoreInfoCount = static_cast<std::uint32_t>(waits.size());
	submit.pWaitSemaphoreInfos = waits.data();
	submit.commandBufferInfoCount = static_cast<std::uint32_t>(commands.size() - (Job.async ? first : 0));
	submit.pCommandBufferInfos = commands.data() + (Job.async ? first : 0);
	submit.signalSemaphoreInfoCount = static_cast<std::uint32_t>(Job.signals.size());
	submit.pSignalSemaphoreInfos = Job.signals.data();
	if (!VK14_VERIFY(vkQueueSubmit2(device.graphics_queue(), count, submits.data(), VK_NULL_HANDLE)))
	{
		Failure = "submitting a frame";
		return false;
	}
	if (lowlatency)
	{
		main->latency_marker(Job.present_id, VK_LATENCY_MARKER_RENDERSUBMIT_END_NV);
	}
	return true;
}

bool vulkan14_renderer::context::present(std::vector<vk14::swapchain *> const &Windows, std::uint64_t const Id)
{
	auto *main{windows.empty() ? nullptr : windows.front().get()};
	auto const withmain{(main != nullptr) && (std::find(Windows.begin(), Windows.end(), main) != Windows.end())};
	auto const generated{withmain ? main->generated_count() : 0u};
	auto const lowlatency{withmain && main->low_latency() && (Id > 0)};
	auto const ids{device.low_latency_enabled()};
	// the frames generated by dlss go first, one after another, then the frame drawn: at equal times over the time of a frame, as
	// measured between the frames the main thread handed over (the guide of the frame generation, 7), and done in time for the
	// next one to be submitted. the main thread meanwhile goes on with the next frame up to its windows; without the render thread
	// they go at once (vsync spaces them)
	auto const start{std::chrono::steady_clock::now()};
	auto const paced{(generated > 0) && render_threaded() && (present_interval > 0.0)};
	auto spacing{0.0};
	if (paced)
	{
		spacing = std::min(present_interval / static_cast<double>(generated + 1), std::max(0.0, 0.95 * present_interval - submit_time) / static_cast<double>(generated));
	}
	auto const step{std::chrono::duration_cast<std::chrono::steady_clock::duration>(std::chrono::duration<double>(spacing))};
	for (std::uint32_t i = 0; i < generated; ++i)
	{
		if (paced && (i > 0))
		{
			wait_until(start + step * i);
		}
		auto const semaphore{main->generated_present_semaphore(i)};
		auto const swapchain{main->handle()};
		auto const image{main->generated_index(i)};
		std::uint64_t const noid{0};
		VkPresentIdKHR presentid{};
		presentid.sType = VK_STRUCTURE_TYPE_PRESENT_ID_KHR;
		presentid.swapchainCount = 1;
		presentid.pPresentIds = &noid;
		VkPresentInfoKHR info{};
		info.sType = VK_STRUCTURE_TYPE_PRESENT_INFO_KHR;
		info.pNext = (ids ? &presentid : nullptr);
		info.waitSemaphoreCount = 1;
		info.pWaitSemaphores = &semaphore;
		info.swapchainCount = 1;
		info.pSwapchains = &swapchain;
		info.pImageIndices = &image;
		auto const result{vkQueuePresentKHR(device.graphics_queue(), &info)};
		main->presented(result);
		if ((result == VK_ERROR_DEVICE_LOST) || (result == VK_ERROR_SURFACE_LOST_KHR))
		{
			vk14::log_error(std::string("vkQueuePresentKHR failed with ") + vk14::result_string(result));
			return false;
		}
	}
	if (paced)
	{
		wait_until(start + step * generated);
	}

	std::vector<VkSemaphore> waits;
	std::vector<VkSwapchainKHR> swapchains;
	std::vector<std::uint32_t> images;
	std::vector<std::uint64_t> presentids;
	std::vector<VkResult> results(Windows.size(), VK_SUCCESS);
	for (auto *window : Windows)
	{
		waits.push_back(window->present_semaphore());
		swapchains.push_back(window->handle());
		images.push_back(window->image_index());
		presentids.push_back(window == main ? Id : 0);
	}
	VkPresentIdKHR presentid{};
	presentid.sType = VK_STRUCTURE_TYPE_PRESENT_ID_KHR;
	presentid.swapchainCount = static_cast<std::uint32_t>(presentids.size());
	presentid.pPresentIds = presentids.data();
	VkPresentInfoKHR info{};
	info.sType = VK_STRUCTURE_TYPE_PRESENT_INFO_KHR;
	info.pNext = (ids ? &presentid : nullptr);
	info.waitSemaphoreCount = static_cast<std::uint32_t>(waits.size());
	info.pWaitSemaphores = waits.data();
	info.swapchainCount = static_cast<std::uint32_t>(swapchains.size());
	info.pSwapchains = swapchains.data();
	info.pImageIndices = images.data();
	info.pResults = results.data();
	if (lowlatency)
	{
		main->latency_marker(Id, VK_LATENCY_MARKER_PRESENT_START_NV);
	}
	auto const result{vkQueuePresentKHR(device.graphics_queue(), &info)};
	if (lowlatency)
	{
		main->latency_marker(Id, VK_LATENCY_MARKER_PRESENT_END_NV);
	}
	for (std::size_t i = 0; i < Windows.size(); ++i)
	{
		Windows[i]->presented(results[i]);
	}
	if ((result == VK_ERROR_DEVICE_LOST) || (result == VK_ERROR_SURFACE_LOST_KHR))
	{
		vk14::log_error(std::string("vkQueuePresentKHR failed with ") + vk14::result_string(result));
		return false;
	}
	return true;
}

void vulkan14_renderer::context::start_render_thread()
{
	render_stop = false;
	render_thread = std::thread([this]() {
		std::unique_lock<std::mutex> lock(render_mutex);
		while (true)
		{
			render_wake.wait(lock, [this]() { return render_stop || render_queued; });
			if (false == render_queued)
			{
				// stopped, with nothing left to do
				break;
			}
			lock.unlock();
			char const *failure{nullptr};
			auto done{false};
			try
			{
				// the frame submitted, the main thread may go on with the next one (wait_submitted()) while the windows are
				// presented: with the frames generated by dlss the presents are spread over the time of a frame
				auto const started{std::chrono::steady_clock::now()};
				done = submit(render_pending, failure);
				submit_time = std::chrono::duration<double>(std::chrono::steady_clock::now() - started).count();
				auto const handed{render_pending.handed};
				if (present_last != std::chrono::steady_clock::time_point{})
				{
					auto const period{std::chrono::duration<double>(handed - present_last).count()};
					present_interval = ((period > 0.0) && (period < 0.25)) ? (present_interval > 0.0 ? 0.9 * present_interval + 0.1 * period : period) : 0.0;
				}
				present_last = handed;
				{
					std::lock_guard<std::mutex> submitted(render_mutex);
					render_submitted = true;
				}
				render_idle.notify_all();
				if (done && (false == render_pending.windows.empty()) && (false == present(render_pending.windows, render_pending.present_id)))
				{
					done = false;
					failure = "presenting";
				}
			}
			catch (std::exception const &Error)
			{
				vk14::log_error(std::string("the render thread failed: ") + Error.what());
				failure = "recording a frame";
			}
			catch (...)
			{
				vk14::log_error("the render thread failed");
				failure = "recording a frame";
			}
			lock.lock();
			if ((false == done) && (render_failure == nullptr))
			{
				render_failure = (failure != nullptr ? failure : "recording a frame");
			}
			render_queued = false;
			render_idle.notify_all();
		}
	});
}

void vulkan14_renderer::context::stop_render_thread()
{
	if (false == render_thread.joinable())
	{
		return;
	}
	{
		std::lock_guard<std::mutex> lock(render_mutex);
		render_stop = true;
	}
	render_wake.notify_all();
	render_thread.join();
}

void vulkan14_renderer::context::hand_over(render_job &&Job)
{
	{
		std::unique_lock<std::mutex> lock(render_mutex);
		render_idle.wait(lock, [this]() { return false == render_queued; });
		render_pending = std::move(Job);
		render_pending.handed = std::chrono::steady_clock::now();
		render_queued = true;
		render_submitted = false;
	}
	render_wake.notify_one();
}

void vulkan14_renderer::context::wait_submitted()
{
	if (false == render_threaded())
	{
		return;
	}
	auto const start{std::chrono::steady_clock::now()};
	std::unique_lock<std::mutex> lock(render_mutex);
	render_idle.wait(lock, [this]() { return (false == render_queued) || render_submitted; });
	render_wait = std::chrono::duration<double, std::milli>(std::chrono::steady_clock::now() - start).count();
}

char const *vulkan14_renderer::context::drain()
{
	if (false == render_threaded())
	{
		return nullptr;
	}
	auto const start{std::chrono::steady_clock::now()};
	std::unique_lock<std::mutex> lock(render_mutex);
	render_idle.wait(lock, [this]() { return false == render_queued; });
	render_wait = std::chrono::duration<double, std::milli>(std::chrono::steady_clock::now() - start).count();
	auto const failure{render_failure};
	render_failure = nullptr;
	return failure;
}

// the parts of the renderer made once the device is there
bool vulkan14_renderer::context::create_core(std::uint32_t const Frames, std::string &Reason)
{
	if (false == memory.create(instance, device, Reason))
	{
		return false;
	}
	if (async_compute)
	{
		// what the passes of the compute queue read and write is shared by the two families
		memory.share_between(device.families().graphics, device.families().compute);
	}
	uploads.init(memory, deletions, device.physical());
	// the textures of the background threads filled by the host, where the device can do it to the layout they're sampled in
	uploads.enable_host_copy(device.caps().host_image_copy && device.caps().host_copy_sampled);
	if (false == sampling.create(device, static_cast<float>(Global.AnisotropicFiltering), Reason, lod_bias))
	{
		return false;
	}
	auto const &limits{device.caps().limits};
	(void)limits;
	// the blocks of the frame are read by the passes of the compute queue too (the async compute)
	auto const ringusage{VK_BUFFER_USAGE_VERTEX_BUFFER_BIT | VK_BUFFER_USAGE_INDEX_BUFFER_BIT | VK_BUFFER_USAGE_UNIFORM_BUFFER_BIT | VK_BUFFER_USAGE_STORAGE_BUFFER_BIT | VK_BUFFER_USAGE_TRANSFER_SRC_BIT};
	if (false == ring.create(memory, ring_size, Frames, ringusage, "frame ring", ring_tail, true))
	{
		Reason = "no ring for the data of the frames";
		return false;
	}
	if ((false == shaders.init(vk14::binding_preamble(device.raytracing_enabled()), Reason)) || (false == pipelines.init(device, Reason)) || (false == passes.create(device, Frames, Reason)))
	{
		return false;
	}
	resources.gpu = &device;
	resources.memory = &memory;
	resources.uploads = &uploads;
	resources.deletions = &deletions;
	resources.sampling = &sampling;
	resources.images = &images;
	resources.thread = std::this_thread::get_id();
	resources.pending = &pending;
	resources.background = (Global.gfx_vulkan_asyncresources ? &background : nullptr);
	resources.raytracing = device.raytracing_enabled();
	textures = std::make_unique<texture_bank>([this]() -> texture_source * { return new vk14::vulkan14_texture(resources); });
	return imgui.create(resources, shaders, pipelines, ring, Reason);
}

// the value of the timeline the gpu reached, 0 when it can't be read
std::uint64_t vulkan14_renderer::context::completed() const
{
	std::uint64_t value{0};
	if ((timeline == VK_NULL_HANDLE) || (vkGetSemaphoreCounterValue(device.handle(), timeline, &value) != VK_SUCCESS))
	{
		return 0;
	}
	lastcompleted = value;
	return value;
}

bool vulkan14_renderer::context::wait(std::uint64_t const Value) const
{
	if ((Value == 0) || (completed() >= Value))
	{
		return true;
	}
	VkSemaphoreWaitInfo wait{};
	wait.sType = VK_STRUCTURE_TYPE_SEMAPHORE_WAIT_INFO;
	wait.semaphoreCount = 1;
	wait.pSemaphores = &timeline;
	wait.pValues = &Value;
	return VK14_VERIFY(vkWaitSemaphores(device.handle(), &wait, UINT64_MAX));
}

void vulkan14_renderer::context::destroy()
{
	auto const handle{device.handle()};
	// the background threads use what goes below
	background.stop();
	// the frame given to the render thread goes to the queue first
	stop_render_thread();
	if (handle != VK_NULL_HANDLE)
	{
		// the end of the renderer, not a frame: everything on the gpu has to be done
		vkDeviceWaitIdle(handle);
	}
	acquired.clear();
	windows.clear();
	imgui.destroy();
	// the textures give their images to the deletion queue, which goes now that the gpu is idle
	textures.reset();
	uploads.end_frame();
	uploads.reset();
	images.clear();
	deletions.flush();
	// the features of dlss released by the deletions above, ngx goes before the device
	dlss.shutdown();
	pipelines.shutdown();
	shaders.shutdown();
	passes.destroy();
	ring.destroy();
	if (handle != VK_NULL_HANDLE)
	{
		sampling.destroy(handle);
		for (auto &frame : frames)
		{
			if (frame.pool != VK_NULL_HANDLE)
			{
				vkDestroyCommandPool(handle, frame.pool, nullptr);
			}
			for (auto &worker : frame.workers)
			{
				vkDestroyCommandPool(handle, worker.pool, nullptr);
			}
			if (frame.compute_pool != VK_NULL_HANDLE)
			{
				vkDestroyCommandPool(handle, frame.compute_pool, nullptr);
			}
		}
		if (timeline != VK_NULL_HANDLE)
		{
			vkDestroySemaphore(handle, timeline, nullptr);
		}
		if (reflex != VK_NULL_HANDLE)
		{
			vkDestroySemaphore(handle, reflex, nullptr);
		}
		if (compute_timeline != VK_NULL_HANDLE)
		{
			vkDestroySemaphore(handle, compute_timeline, nullptr);
		}
	}
	memory.destroy();
	frames.clear();
	timeline = VK_NULL_HANDLE;
	reflex = VK_NULL_HANDLE;
	compute_timeline = VK_NULL_HANDLE;
	async_compute = false;
	device.destroy();
	instance.destroy();
}

