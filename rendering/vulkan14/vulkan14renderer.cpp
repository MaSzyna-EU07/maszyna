// maintenance

void vulkan14_renderer::Update(double const Deltatime)
{
	Update_Pick_Control();
	Update_Pick_Node();
	update_screenshot();

	m_updateaccumulator += Deltatime;
	if (m_updateaccumulator < 1.0)
	{
		// too early for any work
		return;
	}
	m_updateaccumulator = 0.0;
	m_framerate = 1000.f / Timer::subsystem.mainloop_total.average();

	// adjust draw ranges etc, based on recent performance (opengl46_renderer::Update())
	if (Global.targetfps != 0.0f)
	{
		float fps_diff = Global.targetfps - m_framerate;
		if (fps_diff > 0.0f)
			Global.fDistanceFactor = std::max(0.5f, Global.fDistanceFactor - 0.05f);
		else
			Global.fDistanceFactor = std::min(Global.gfx_distance_factor_max, Global.fDistanceFactor + 0.05f);
	}
	// legacy framerate parameters
	else if (Global.fFpsAverage != 0.f)
	{
		auto const fps_diff = m_framerate - Global.fFpsAverage;
		if (fps_diff < -Global.fFpsDeviation)
		{
			Global.fDistanceFactor = std::min(std::max(1.0f, Global.fDistanceFactor - 0.05f), Global.gfx_distance_factor_max);
		}
		else if (fps_diff > Global.fFpsDeviation)
		{
			Global.fDistanceFactor = std::min(std::min(3.0f, Global.fDistanceFactor + 0.05f), Global.gfx_distance_factor_max);
		}
	}

	if (Global.UpdateMaterials)
	{
		// update resources if there was environmental change
		simulation_state simulationstate{Global.Weather, Global.Season};
		std::swap(m_simulationstate, simulationstate);
		if ((m_simulationstate.season != simulationstate.season) && (false == simulationstate.season.empty()))
		{
			m_materials.on_season_change();
		}
		if ((m_simulationstate.weather != simulationstate.weather) && (false == simulationstate.weather.empty()))
		{
			m_materials.on_weather_change();
		}
		if (((m_simulationstate.season != simulationstate.season) && (false == simulationstate.season.empty())) ||
		    ((m_simulationstate.weather != simulationstate.weather) && (false == simulationstate.weather.empty())))
		{
			// the heightmap terrain keeps copies of the textures of its layer materials
			if (m_context && m_context->scene.terrain)
			{
				m_context->scene.terrain->on_environment_change();
			}
			// the seasonal variants of the models are shown and hidden anew: the walks kept by the gpu culling go
			m_walkrecords.clear();
		}
	}

	if (m_context && m_context->textures && (true == Global.ResourceSweep) && (true == simulation::is_ready))
	{
		// garbage collection
		m_geometry.update();
		m_context->textures->update();
	}
	if ((Global.gfx_texture_releasedistance > 0.f) && (true == simulation::is_ready))
	{
		update_texture_release();
	}
	update_info();
}

void vulkan14_renderer::update_info()
{
	m_infotimes.clear();
	m_infostats.clear();
	if (!m_context)
	{
		return;
	}
	auto const &ctx{*m_context};
	auto const &caps{ctx.device.caps()};
	m_infotimes = "vulkan " + vk14::version_string(caps.api_version) + ": " + caps.device_name + " (" + caps.driver_name + ")\n" + "frames: " + std::to_string(ctx.framecount) + ", in flight " + std::to_string(ctx.frames.size()) + "\n" +
	              "mainloop total: " + to_string(Timer::subsystem.mainloop_total.average(), 2) + " ms, frame cpu: " + to_string(Timer::subsystem.gfx_total.average(), 2) + " ms, ui: " + to_string(Timer::subsystem.gfx_gui.average(), 2) +
	              " ms, present: " + to_string(Timer::subsystem.gfx_swap.average(), 2) + " ms\n" + "command buffers recorded: " + to_string(ctx.record_time, 2) + " ms, " + std::to_string(ctx.record_calls) + " calls in " +
	              std::to_string(ctx.record_chunks) + " chunks, " + std::to_string(ctx.record_threads) + (ctx.record_threads == 1 ? " thread" : " threads") +
	              (ctx.render_threaded() ? ", on the render thread; waited for it: " + to_string(ctx.render_wait, 2) + " ms\n" : "\n") + "gpu frame parts:\n" + ctx.passes.info();
	VkDeviceSize usage{0}, budget{0};
	ctx.memory.budget(usage, budget);
	m_infostats = "device memory: " + vk14::memory_size_string(usage) + " of " + vk14::memory_size_string(budget) + (ctx.device.memory_budget_enabled() ? "" : " (no budget from the driver)") + "\n" + "images: " + std::to_string(ctx.images.size()) +
	              ", uploaded " + vk14::memory_size_string(ctx.uploads.uploaded()) + ", waiting for the gpu to be deleted: " + std::to_string(ctx.deletions.size()) + "\n" + (ctx.textures ? ctx.textures->info() + "\n" : std::string{}) + ctx.shaders.info() +
	              "\n" + ctx.pipelines.info() + "\n" + background_info() + "frame ring: " + vk14::memory_size_string(ctx.ring.used()) + " of " + vk14::memory_size_string(ctx.ring.capacity()) + "\n";
	for (auto const &window : ctx.windows)
	{
		auto const extent{window->extent()};
		m_infostats += "window: " + std::to_string(extent.width) + "x" + std::to_string(extent.height) + (window->srgb() ? ", srgb" : ", unorm") + (window->present_mode() == VK_PRESENT_MODE_FIFO_KHR ? ", vsync" : ", no vsync") + "\n";
	}
	if (false == m_viewports.empty())
	{
		auto const &main{m_viewports.front()};
		m_infostats += "scene drawn at " + std::to_string(main.width) + "x" + std::to_string(main.height) + (dlss_active() ? ", " + ctx.dlss.info() : std::string{}) + "\n";
	}
	// the statistics of the scene and of the cullings, as the opengl renderer gives them
	collect_cluster_stats();
	m_infostats += "\n" + scene_info() + cull_info();
}

std::string vulkan14_renderer::background_info() const
{
	auto const &ctx{*m_context};
	std::string info;
	if (ctx.background.running())
	{
		auto const pending{ctx.pending.made_count.load()};
		info += "background threads: " + std::to_string(ctx.background.pending()) + " tasks waiting; pipelines made ahead: " + std::to_string(ctx.warm_made.load()) + ", made late: " +
		        std::to_string(ctx.pipelines_late.load()) + "; textures made: " + std::to_string(pending) + ", draws without theirs: " + std::to_string(ctx.pending.late_count.load()) + "\n";
	}
	else
	{
		info += "background threads: off (gfx.vulkan.asyncresources)\n";
	}
	if (ctx.walks.running())
	{
		info += "walkers: " + std::to_string(m_walkpasses) + " passes in the last frame, " + std::to_string(vk14::walk_threads()) + (vk14::walk_threads() == 1 ? " thread" : " threads") +
		        ", the main thread waited for them: " + to_string(m_walkwait, 2) + " ms\n";
	}
	else
	{
		info += "walkers: off (gfx.vulkan.parallelpasses)\n";
	}
	if (ctx.models.running())
	{
		info += "helpers of the walks: " + std::to_string(m_helpedgroups) + " groups of the cullings walked by them in the last frame\n";
	}
	else
	{
		info += "helpers of the walks: off (gfx.vulkan.parallelmodels)\n";
	}
	if (ctx.async_compute)
	{
		info += std::string("async compute: the sky and the weather on the compute queue (family ") + std::to_string(ctx.device.families().compute) + "), " +
		        (m_asyncframe ? "in the last frame" : "not in the last frame") + "\n";
	}
	else
	{
		info += (Global.gfx_vulkan_asynccompute ? "async compute: off (no compute family of its own)\n" : "async compute: off (gfx.vulkan.asynccompute)\n");
	}
	return info;
}

